"use strict";
const assert = require('node:assert/strict');
module.exports = async ({ win, fixture, evaluate, click, waitFor, screenshot, prefix }) => {
  const js = script => evaluate(win, script);
  const tap = selector => click(win, selector);
  const until = script => waitFor(win, script, 'run picker');
  const patches = () => fixture.requests.filter(r => r.method === 'PATCH' && r.path === '/api/conversations/A');
  const settled = async () => until("!state.chat.modelSaving && document.querySelector('.run-picker-popup').getAttribute('aria-busy')==='false'");
  const fit = async () => {
    assert.equal(await js(`(() => {const p=document.querySelector('.run-picker-popup'), r=p.getBoundingClientRect();return r.x>=0 && r.y>=0 && r.right<=innerWidth && r.bottom<=innerHeight && p.scrollWidth<=p.clientWidth;})()`), true);
  };
  assert.equal(await js("document.querySelectorAll('[data-hs-for=chatModel],[data-hs-for=chatEffort],[data-hs-for=chatPermMode]').length"), 0, 'no legacy dropdown wrappers');
  await js("document.querySelector('#chatInput').value='未发送的草稿，不要覆盖'");
  const start = patches().length;
  await tap('#chatRunPicker .rp-model'); await until("!!document.querySelector('.rp-range')");
  assert.equal(patches().length, start, 'opening never changes defaults');
  await fit(); await screenshot(win, `${prefix}-picker-effort.png`);
  await js("(() => {const s=document.querySelector('.rp-range');for(const value of [0,1,2,0]){s.value=value;s.dispatchEvent(new Event('input',{bubbles:true}));}})()");
  assert.equal(patches().length, start, 'drag preview is local and does not flood the API');
  await js("document.querySelector('.rp-range').dispatchEvent(new Event('change',{bubbles:true}))");
  await settled();
  assert.equal(patches().length, start + 1); assert.deepEqual(patches().at(-1).body, { reasoningEffort: 'low' });
  assert.equal(await js("state.chat.reasoningEffort"), 'low');
  await tap('.rp-reset'); await settled(); assert.deepEqual(patches().at(-1).body, { reasoningEffort: null });
  assert.equal(await js("document.querySelector('.rp-effort-title').textContent"), 'High', 'reset follows the Agent/model default');
  await tap('.rp-model-link'); await fit(); await screenshot(win, `${prefix}-picker-models.png`);
  await js("document.querySelector('.rp-search').value='搜索测试连接';document.querySelector('.rp-search').dispatchEvent(new Event('input',{bubbles:true}))");
  assert.equal(await js("document.querySelectorAll('.rp-option').length"), 10, 'search also matches a connection label');
  await js("document.querySelector('.rp-search').value='nothing-matches';document.querySelector('.rp-search').dispatchEvent(new Event('input',{bubbles:true}))");
  assert.match(await js("document.querySelector('.rp-options').textContent"), /没有匹配/);
  await js("document.querySelector('.rp-search').value='';document.querySelector('.rp-search').dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('.rp-option').focus()");
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Down' });
  await until("document.activeElement===document.querySelectorAll('.rp-option')[1]");
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'End' });
  await until("document.activeElement===Array.from(document.querySelectorAll('.rp-option')).at(-1)");
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Home' });
  await until("document.activeElement===document.querySelector('.rp-option')");
  await tap('.rp-option[data-value="mock/small"]'); await settled();
  assert.equal(await js("state.chat.model"), 'mock/small');
  assert.deepEqual(patches().at(-1).body, { modelRef: 'mock/small' });
  assert.equal(await js("document.querySelector('#chatRunPicker .rp-model-label').textContent"), '32K 测试模型');
  await tap('#chatRunPicker .rp-mode'); await fit(); await screenshot(win, `${prefix}-picker-modes.png`);
  assert.match(await js("document.querySelector('.rp-option[data-value=dontAsk]').innerText"), /未获授权/);
  assert.match(await js("document.querySelector('.rp-option[data-value=bypassPermissions]').innerText"), /Harbour/);
  await tap('.rp-option[data-value=plan]'); await until("document.querySelector('.run-picker-popup').hidden && !state.chat.modelSaving");
  assert.deepEqual(patches().at(-1).body, { permissionMode: 'plan' });
  assert.equal(await js("document.querySelector('#chatRunPicker .rp-mode-label').textContent"), '仅规划');
  await tap('#chatRunPicker .rp-mode'); fixture.failNextPatch(); await tap('.rp-option[data-value=default]');
  await until("document.querySelector('.rp-note').dataset.error==='true' && !state.chat.modelSaving");
  assert.equal(await js("state.chat.permissionMode"), 'plan', 'failed write rolls back the displayed selection');
  await tap('.rp-option[data-value=default]'); await until("document.querySelector('.run-picker-popup').hidden");
  assert.equal(await js("state.chat.permissionMode"), 'default');
  await tap('#chatRunPicker .rp-model'); await until("!!document.querySelector('.rp-range')");
  const beforeLock = patches().length;
  await js("state.chat.running=true;syncChatControlLocks()");
  assert.equal(await js("document.querySelector('.rp-range').disabled"), true);
  await js("document.querySelector('.rp-range').value=0;document.querySelector('.rp-range').dispatchEvent(new Event('change',{bubbles:true}))");
  assert.equal(patches().length, beforeLock, 'programmatic change cannot evade a live run lock');
  await js("state.chat.running=false;syncChatControlLocks();document.querySelector('.rp-range').focus()");
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' });
  await until("document.querySelector('.run-picker-popup').hidden");
  assert.equal(await js("document.activeElement===document.querySelector('#chatRunPicker .rp-model')"), true, 'Escape restores the trigger');
  await tap('#chatRunPicker .rp-model'); await until("!!document.querySelector('.rp-range')");
  await js("state.chat.readOnlyMirror=true;syncChatControlLocks()");
  assert.equal(await js("document.querySelector('.run-picker-popup').hidden && document.querySelector('#chatRunPicker .rp-model').disabled"), true);
  await js("state.chat.readOnlyMirror=false;syncChatControlLocks()");
  assert.equal(await js("document.querySelector('#chatInput').value"), '未发送的草稿，不要覆盖');
  assert.equal(fixture.requests.some(r => r.path === '/api/run'), false, 'zero model runs');
  assert.deepEqual(await js('window.__testErrors'), []);
  console.log(`RUN_PICKER_OK ${prefix}: shared picker, preview/commit/reset, failure rollback, session-only patches, keyboard, read-only and live locks; no models`);
};
