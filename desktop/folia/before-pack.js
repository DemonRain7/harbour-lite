const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { pathToFileURL } = require('node:url');
const { prepare, npm, root, applyDependencyPatches } = require('../../scripts/prepare-folia.cjs');

// Target-specific production dependencies; never ship a second Electron runtime.
module.exports = async function beforePack(context) {
  const arch = ['ia32', 'x64', 'armv7l', 'arm64', 'universal'][context.arch];
  const platform = context.electronPlatformName;
  if (!arch || arch === 'universal') throw new Error('请分别构建 x64 / arm64 Folia 资源');
  if (platform !== process.platform) throw new Error('Folia 桌面包须在目标系统构建；Mac 请在 Mac 执行 build:mac。');
  prepare();
  const stageRoot = path.resolve(__dirname, '../.folia-package');
  const target = path.join(stageRoot, arch);
  // Only replace this hook's generated stage; never remove an arbitrary directory.
  if (path.dirname(target) !== stageRoot) throw new Error('Invalid Folia staging path');
  const marker = path.join(target, '.harbour-folia-stage');
  if (fs.existsSync(target)) {
    if (!fs.existsSync(marker)) throw new Error(`Refusing to replace unowned Folia stage: ${target}`);
    fs.rmSync(target, { recursive: true });
  }
  fs.mkdirSync(target, { recursive: true });
  fs.writeFileSync(marker, 'generated by Harbour Folia beforePack');
  for (const name of ['dist', 'electron', 'shared', 'build', 'packaging', 'patches', 'package.json', 'package-lock.json', 'LICENSE', 'UPSTREAM.json']) {
    const source = path.join(root, name);
    if (fs.existsSync(source)) fs.cpSync(source, path.join(target, name), { recursive: true, filter: file => {
      if (file.includes(`${path.sep}target${path.sep}`) || file.endsWith(`${path.sep}target`)) return false;
      // The target FFmpeg runtime is copied below; don't also ship build caches
      // for this or previously built architectures.
      return name !== 'build' || path.relative(source, file).split(path.sep)[0] !== 'ffmpeg';
    } });
  }
  npm(['ci', '--omit=dev', '--ignore-scripts', '--no-audit', '--no-fund', `--os=${platform}`, `--cpu=${arch}`], target);
  applyDependencyPatches(target, { toolRoot: root });
  const { prepareBundledFfmpeg, resolveFfmpegAsset } = await import(pathToFileURL(path.join(root, 'packaging/ffmpeg/fetch-ffmpeg.mjs')).href);
  const outputRoot = path.join(root, 'build/ffmpeg');
  await prepareBundledFfmpeg({ platform, arch, outputRoot });
  fs.cpSync(path.join(outputRoot, resolveFfmpegAsset(platform, arch).key), path.join(target, 'ffmpeg-audio'), { recursive: true });
  if (platform === 'win32') {
    if (!require('./windows-helper').prepareWindowsHelper(root, { platform, arch })) {
      if (arch !== process.arch) throw new Error('Windows 壁纸助手需在目标架构构建，不能混入宿主架构二进制。');
      const result = spawnSync(process.execPath, [path.join(root, 'packaging/windows/build-wallpaper-helper.mjs')], { cwd: root, stdio: 'inherit', windowsHide: true });
      if (result.status !== 0) throw new Error('Windows 壁纸助手构建失败；此架构需 Rust/MSVC 工具链。');
    }
    fs.copyFileSync(path.join(root, 'build/folia-wallpaper-helper.exe'), path.join(target, 'build/folia-wallpaper-helper.exe'));
    fs.copyFileSync(path.join(__dirname, 'vendor/windows-wallpaper/provenance.json'), path.join(target, 'build/folia-wallpaper-helper.provenance.json'));
  }
};
